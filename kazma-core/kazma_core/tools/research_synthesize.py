"""LLM synthesis over saved research digests / extracts."""

from __future__ import annotations

import asyncio
import logging
import os
from pathlib import Path

__all__ = ["synthesize_from_digests"]

logger = logging.getLogger(__name__)


def _env_int(name: str, default: int, *, lo: int, hi: int) -> int:
    raw = (os.environ.get(name) or "").strip()
    if not raw:
        return default
    try:
        return max(lo, min(hi, int(raw)))
    except ValueError:
        return default


def _workspace_root() -> Path:
    # The binding ladder ends in the default sandbox under data_dir() and does
    # not raise short of an unwritable data dir; the old CWD-relative
    # fallback only ever fired then, and pointed somewhere else entirely.
    from kazma_core.tools.file_write import _get_workspace

    return _get_workspace().resolve()


def _resolve_under_workspace(path: str) -> Path | str:
    raw = (path or "").strip().replace("\\", "/")
    if not raw:
        return "Error: empty path"
    p = Path(raw)
    if not p.is_absolute():
        p = _workspace_root() / p
    try:
        resolved = p.resolve()
        root = _workspace_root()
        resolved.relative_to(root)
    except Exception:
        return f"Error: path must be under workspace ({_workspace_root()})"
    # Kazma's own databases are refused here as at every other door
    # (store_registry, AGENTS.md section 37): on an install whose workspace
    # holds kazma-data/, these read-tier readers returned raw store bytes
    # that file_read refuses (audit 2026-10-26 AUD-086).
    from kazma_core.store_registry import is_kazma_store, store_refusal

    if is_kazma_store(resolved):
        return "Error: " + store_refusal(resolved, door="research readers")
    if not resolved.is_file():
        return f"Error: file not found: {path}"
    return resolved


def _load_body(path: str) -> str | None:
    resolved = _resolve_under_workspace(path)
    if isinstance(resolved, str):
        return None
    try:
        return resolved.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return None


#: The words the research report writes itself, per language (FA-238: an
#: Arabic question got an English report, its headings included).
REPORT_WORDS: dict[str, dict[str, str]] = {
    "en": {
        "synthesis": "Research synthesis", "question": "Question", "loaded": "Sources loaded",
        "report": "Research report", "log": "Pipeline log", "claims": "Evidence claims",
        "generated": "Generated by Kazma research pipeline",
        "outline": ("## Executive summary\n## Background\n## Key findings\n"
                    "## Comparison / alternatives\n## Risks and open questions\n"
                    "## Conclusions\n## Sources\n"),
    },
    "ar": {
        "synthesis": "خلاصة البحث", "question": "السؤال", "loaded": "المصادر المحمّلة",
        "report": "تقرير بحثي", "log": "سجل خطوات البحث", "claims": "الأدلة المستخرجة",
        "generated": "أعدّه خط البحث في Kazma",
        "outline": ("## الملخص التنفيذي\n## الخلفية\n## النتائج الرئيسية\n"
                    "## المقارنة والبدائل\n## المخاطر والأسئلة المفتوحة\n"
                    "## الخلاصة\n## المصادر\n"),
    },
}

#: Names of the languages a report can be asked in, for the model.
_LANGUAGE_NAMES = {"ar": "Arabic (Modern Standard Arabic)", "en": "English"}


def report_language(topic: str, language: str = "") -> str:
    """The report's language: *language* when given (``ar``/``en``, or a
    name), else the topic's own (Arabic when Arabic dominates it)."""
    given = (language or "").strip().lower()
    if given in ("ar", "arabic", "العربية", "عربي"):
        return "ar"
    if given in ("en", "english"):
        return "en"
    if given:
        return given
    from kazma_core.documents.arabic import is_rtl_dominant

    return "ar" if is_rtl_dominant(topic or "") else "en"


def report_words(language: str) -> dict[str, str]:
    """The report's own words in *language* (English for one without them)."""
    return REPORT_WORDS.get(language, REPORT_WORDS["en"])


async def synthesize_from_digests(
    paths: str | list[str],
    question: str,
    outline: str = "",
    max_chars: int = 20_000,
    language: str = "",
    work_id: str = "",
    source_count: int | None = None,
) -> str:
    """Synthesize a multi-source analysis from saved research files.

    Nested LLM call (reduce step). Paths are workspace-relative research
    extracts/digests. Returns markdown with sections and URL citations when
    present in the sources. *language* (``report_language``) is the one the
    analysis is written in; the question's own when not given.
    *source_count*: the first that many paths are the sources, the rest the
    run's own evidence (its claims file); "Sources loaded" counts sources
    only (2026-11, FA-240: it read "4/4" over three sources).
    """
    q = (question or "").strip()
    if not q:
        return "Error: question is required."

    if isinstance(paths, str):
        # comma or newline separated
        path_list = [p.strip() for p in re_split_paths(paths) if p.strip()]
    else:
        path_list = [str(p).strip() for p in (paths or []) if str(p).strip()]
    if not path_list:
        return "Error: provide one or more research file paths."

    cap_in = _env_int("KAZMA_RESEARCH_SYNTH_MAX_IN", 48_000, lo=4000, hi=200_000)
    cap_out = max(2000, min(50_000, int(max_chars or 20_000)))

    blocks: list[str] = []
    used = 0
    loaded = 0
    for i, pth in enumerate(path_list[:20], 1):
        body = await asyncio.to_thread(_load_body, pth)
        if body is None:
            blocks.append(f"### Source {i}: {pth}\n_(failed to load)_\n")
            continue
        # Prefer existing digest if huge raw file
        if len(body) > 20_000:
            try:
                from kazma_core.tools.read_url import digest_research_file

                dig = await digest_research_file(pth)
                if dig and not dig.startswith("Error:"):
                    body = dig
            except Exception:
                body = body[:16_000]
        piece = f"### Source {i}: `{pth}`\n\n{body.strip()}\n"
        if used + len(piece) > cap_in:
            remain = max(0, cap_in - used - 200)
            if remain > 500:
                blocks.append(piece[:remain] + "\n… [truncated]\n")
            break
        blocks.append(piece)
        used += len(piece)
        if source_count is None or i <= source_count:
            loaded += 1

    if loaded == 0:
        return "Error: could not load any source files under the workspace."

    lang = report_language(q, language)
    words = report_words(lang)
    outline_block = f"\nTarget outline:\n{outline.strip()}\n" if outline.strip() else ""
    write_in = (
        f"- Write the whole analysis in {_LANGUAGE_NAMES.get(lang, lang)}, headings "
        "included, whatever language the sources are in; keep URLs, file paths, code "
        "and proper names as they are.\n"
    )
    system = (
        "You are a research analyst. Using ONLY the source materials provided, "
        "write a rigorous multi-section analysis. Requirements:\n"
        "- Use clear markdown headings (## / ###).\n"
        "- Cite sources inline with URLs or file paths from the materials "
        "(prefer http URLs when present).\n"
        "- Prefer claims listed under Evidence claims when present; "
        "do not invent facts not supported by materials.\n"
        "- Call out conflicts between sources.\n"
        "- End with a Sources section listing files/URLs used.\n"
        + write_in
        + f"- Keep under ~{cap_out} characters."
    )
    user = (
        f"Research question:\n{q}\n{outline_block}\n"
        f"## Source materials\n\n{''.join(blocks)}"
    )

    try:
        from kazma_core.web_acquire.research_llm import resolved_route
        from kazma_core.web_acquire.crawl_jobs import call
        route = await call(resolved_route)
        if route is not None:
            client, model, frozen_failover = route
        else:
            from kazma_core.model_registry import get_model_registry
            reg = get_model_registry()
            client = reg.get_client()
            model = None
            try:
                model = (reg.get_active_profile() or {}).get('model')
            except Exception:
                pass
            frozen_failover = None
        messages = [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ]
        # Resilient path (audit): transient retries + failover + ledger.
        from kazma_core.agent.resilient_chat import resilient_chat

        result = await resilient_chat(
            client,
            messages=messages,
            tools=None,
            model=model,
            max_attempts=3,
            max_tokens=min(8000, max(1024, cap_out // 3)),
            label="research-synthesize",
            thread_id=work_id,  # the ledger's work (FA-260)
            frozen_failover=frozen_failover,
            # A thinking model's hidden reasoning counts against max_tokens:
            # live 2026-10-31 deepseek-flash spent all 8,000 on it, then
            # 11,015 of the 16,000 retry, and the report was cut off --
            # one deep research in two failed at its last step.
            reasoning="off",
        )
        text = ""
        if hasattr(result, "content"):
            text = str(result.content or "")
        elif isinstance(result, dict):
            text = str(result.get("content") or "")
        else:
            text = str(result or "")
        text = text.strip()
        if not text:
            return "Error: synthesis returned empty content."
        if len(text) > cap_out:
            text = text[: cap_out - 40] + "\n\n… [synthesis truncated]"
        header = (
            f"# {words['synthesis']}\n\n"
            f"**{words['question']}:** {q}\n"
            f"**{words['loaded']}:** {loaded}/{len(path_list) if source_count is None else source_count}\n\n"
        )
        return header + text
    except Exception as exc:
        logger.warning("[synthesize_from_digests] failed: %s", exc)
        return f"Error: synthesis failed — {type(exc).__name__}: {exc}"


def re_split_paths(s: str) -> list[str]:
    out: list[str] = []
    for line in s.replace(",", "\n").splitlines():
        t = line.strip().strip('"').strip("'")
        if t:
            out.append(t)
    return out
